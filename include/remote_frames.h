/** @brief Captured command name, display hex, 50 measured pulses and repeat count.
 * 已采集命令名、显示用十六进制、50 段实测脉冲与重复数。 */
struct Frame { const char* name; const char* hex; const Pulse* pulses; uint8_t repeats; };
inline constexpr Frame kFrames[] = {
    {"power", "FFFF02", kFrame_power, replay_config::kRepeats},
    {"brightness_up", "FFFF0A", kFrame_brightness_up, replay_config::kAdjustmentRepeats},
    {"brightness_down", "FFFF0C", kFrame_brightness_down, replay_config::kAdjustmentRepeats},
    {"cct_up", "FFFF12", kFrame_cct_up, replay_config::kAdjustmentRepeats},
    {"cct_down", "FFFF10", kFrame_cct_down, replay_config::kAdjustmentRepeats},
    {"night_mode", "FFFF04", kFrame_night_mode, replay_config::kRepeats},
    {"timer_10min", "FFFF06", kFrame_timer_10min, replay_config::kRepeats},
};
/** @brief Find an exact built-in command name; unknown names return nullptr.
 * 按精确名称查找内置命令；未知名称返回 nullptr。
 * @param name Non-null NUL-terminated name. / 非空且 NUL 结尾的名称。
 * @return Static frame pointer or nullptr. / 静态帧指针或 nullptr。 */
inline const Frame* findFrame(const char* name) {
  for (const auto& frame : kFrames) if (std::strcmp(name, frame.name) == 0) return &frame;
  return nullptr;
}
